using NnmAdvisory.Api.Models;

namespace NnmAdvisory.Api.Repositories;

/// <summary>
/// Data-access contract for persisting <see cref="ContactSubmission"/> rows
/// in the <c>contact_submissions</c> table.
///
/// All writes execute as parameterised SQL through EF Core (Requirement 11.3)
/// and are committed atomically: if the write fails for any reason the entire
/// transaction is rolled back and no rows are left changed (Requirement 11.5).
///
/// The repository layer keeps the service layer free of EF Core /
/// infrastructure concerns (Requirement 10.1).
/// </summary>
public interface IContactRepository
{
    /// <summary>
    /// Inserts a new contact form submission.
    ///
    /// The <see cref="ContactSubmission.SubmittedAt"/> field is stamped with
    /// the current UTC time at insert time (Requirement 11.6), and the primary
    /// key is generated by the database.
    ///
    /// The insert is wrapped in a transaction by EF Core's
    /// <c>SaveChangesAsync</c>; if it fails (constraint violation, system
    /// error, or lost connection) the transaction is rolled back, no row is
    /// persisted, and the originating exception propagates to the caller
    /// (Requirement 11.5).
    /// </summary>
    /// <param name="submission">The submission to persist. Must not be null.</param>
    /// <param name="cancellationToken">A token to cancel the asynchronous operation.</param>
    /// <returns>The persisted entity, including its database-generated identifier.</returns>
    Task<ContactSubmission> AddAsync(
        ContactSubmission submission,
        CancellationToken cancellationToken = default);
}
